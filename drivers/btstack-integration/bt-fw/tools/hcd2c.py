#!/usr/bin/env python
"""Convert a Bluetooth controller patch file (.hcd) into a C source file.

The Bluetooth controller patch data (.hcd) is a binary blob that is loaded
into the controller over HCI.  The BTStack integration expects it as a C
array (brcm_patchram_buf) so that it can be linked into the application
image, together with the version string (brcm_patch_version) and the
format flag (brcm_patchram_format).

This script generates that C file from the .hcd at build time, so the
package only ships the binary patch data and the C file is never
redistributed.

The output format is byte-for-byte identical to the Infineon reference
file btfw.c, so that a generated file can be compared against the
reference.

Usage:
    python hcd2c.py <input.hcd> <output.c> [--version <version string>]
"""

import argparse
import sys

PY3 = sys.version_info[0] >= 3


def _open_text_write(path):
    # builtin open() in Python 2.7 has no `newline` argument.
    # py3: text mode + newline="\n" keeps LF on Windows.
    # py2: binary mode avoids "\n" -> "\r\n" translation.
    # Generated C file is ASCII only, so both are equivalent.
    if PY3:
        return open(path, "w", newline="\n", encoding="utf-8")
    else:
        return open(path, "wb")

# Format flag written into the generated file.  0x01 is the HCD format
# used by the BRCM patch RAM download path (cybt_prm_download with
# CYBT_PRM_FORMAT_HCD).
BRCM_PATCHRAM_FORMAT = 0x01

# Number of bytes per line in the generated array.
BYTES_PER_LINE = 16

HEADER = """\
/*
 * $ Copyright (C) 2020-2021 Infineon Technologies AG $
 *
 * This file is generated by hcd2c.py from {source}.
 * Do not edit it by hand; edit the .hcd and rebuild instead.
 *
 * The Bluetooth controller patch data below is a binary blob owned by
 * Infineon Technologies AG (formerly Cypress Semiconductor).  It is
 * distributed under the Infineon End User License Agreement; see
 * LICENSE.txt in the parent directory.
 */

#include <stdint.h>

/* labelling: appname-(chipname)(stepping)-frequency-(headset GIT SHA)-(generating SDK version)-\
                                                                            Wiced-release.hcd */
const char brcm_patch_version[] = "{version}";
const uint8_t brcm_patchram_format = 0x{format:02X};
/* Configuration Data Records (Write_RAM) */
#ifndef FW_DATBLOCK_SEPARATE_FROM_APPLICATION
const uint8_t brcm_patchram_buf[] =
{{
"""

FOOTER = """\
};

const int brcm_patch_ram_length = sizeof(brcm_patchram_buf);
#endif /* FW_DATBLOCK_SEPARATE_FROM_APPLICATION */
"""


def format_array(data):
    """Format the binary data as the C array body."""
    # py2: read() returns str, iterating yields 1-char str;
    # bytearray() normalizes to int on both py2/py3.
    data = bytearray(data)
    lines = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset:offset + BYTES_PER_LINE]
        row = " ".join("0x%02X," % b for b in chunk)
        if offset + BYTES_PER_LINE >= len(data):
            # No trailing comma on the last row, like the reference file.
            row = row.rstrip(",")
        lines.append("    " + row)
    return "\n".join(lines)


def generate(hcd_path, output_path, version=""):
    """Generate the C file from the .hcd patch data.

    Returns the number of patch bytes written.
    """
    with open(hcd_path, "rb") as f:
        data = f.read()

    if not data:
        raise ValueError("input .hcd is empty: %s" % hcd_path)

    try:
        source = hcd_path.replace("\\", "/").rsplit("/", 1)[-1]
    except (AttributeError, TypeError):
        source = str(hcd_path)

    with _open_text_write(output_path) as f:
        f.write(HEADER.format(
            source=source,
            version=version,
            format=BRCM_PATCHRAM_FORMAT))
        f.write(format_array(data))
        f.write("\n")
        f.write(FOOTER)

    return len(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("hcd", help="input .hcd patch file")
    parser.add_argument("output", help="output .c file")
    parser.add_argument(
        "--version",
        default="",
        help="patch version string written to brcm_patch_version")
    args = parser.parse_args()

    try:
        size = generate(args.hcd, args.output, args.version)
    except (IOError, OSError, ValueError) as e:
        sys.stderr.write("error: %s\n" % e)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())